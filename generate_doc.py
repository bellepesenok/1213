def set_cell_or_run_cjk(run):
    run.font.name = 'Times New Roman'
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.get_or_add_rFonts()
    rFonts.set(qn('w:eastAsia'), 'SimSun')


def add_title(text_ru, text_zh):
    h = doc.add_heading(level=0)
    run = h.add_run(text_ru + '\n' + text_zh)
    set_cell_or_run_cjk(run)
    h.alignment = WD_ALIGN_PARAGRAPH.CENTER


def add_h1(text):
    h = doc.add_heading(level=1)
    run = h.add_run(text)
    set_cell_or_run_cjk(run)


def add_h2(text):
    h = doc.add_heading(level=2)
    run = h.add_run(text)
    set_cell_or_run_cjk(run)


def add_para(text, bold=False, italic=False, color=None):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.bold = bold
    run.italic = italic
    if color:
        run.font.color.rgb = color
    set_cell_or_run_cjk(run)
    return p


def add_bullet(text):
    p = doc.add_paragraph(style='List Bullet')
    run = p.add_run(text)
    set_cell_or_run_cjk(run)
    return p


def add_lang_block(ru_lines, zh_lines):
    """Add a paired Russian / Chinese explanation block."""
    add_para('Русский:', bold=True, color=RGBColor(0x1F, 0x4E, 0x79))
    for line in ru_lines:
        if line.startswith('•'):
            add_bullet(line[1:].strip())
        else:
            add_para(line)
    add_para('中文：', bold=True, color=RGBColor(0xC0, 0x00, 0x00))
    for line in zh_lines:
        if line.startswith('•'):
            add_bullet(line[1:].strip())
        else:
            add_para(line)
    doc.add_paragraph()



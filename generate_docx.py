def run(text: str, *, bold: bool = False, size: int | None = None) -> str:
    props = [
        '<w:rFonts w:ascii="Times New Roman" w:hAnsi="Times New Roman" w:eastAsia="SimSun" w:cs="Times New Roman"/>'
    ]
    if bold:
        props.append("<w:b/>")
    if size is not None:
        props.append(f'<w:sz w:val="{size * 2}"/>')
        props.append(f'<w:szCs w:val="{size * 2}"/>')
    return (
        "<w:r><w:rPr>"
        + "".join(props)
        + '</w:rPr><w:t xml:space="preserve">'
        + escape(text)
        + "</w:t></w:r>"
    )


def paragraph(text: str, *, style: str | None = None, bold: bool = False, size: int | None = None) -> str:
    style_xml = f'<w:pPr><w:pStyle w:val="{style}"/></w:pPr>' if style else ""
    return f"<w:p>{style_xml}{run(text, bold=bold, size=size)}</w:p>"



from docx.oxml.ns import qn


def set_eastasia_font(style, font_name="SimSun"):
    """Назначает восточноазиатский шрифт стилю для корректного показа иероглифов."""
    rpr = style.element.get_or_add_rPr()
    rfonts = rpr.get_or_add_rFonts()
    rfonts.set(qn("w:eastAsia"), font_name)


def main():
    doc = Document()

    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(12)
    set_eastasia_font(style, "SimSun")

    # Заголовок документа
    title = doc.add_heading("", level=0)
    run = title.add_run("Подробные объяснения к слайдам презентации")
    run.font.size = Pt(20)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER

    sub = doc.add_paragraph()
    sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = sub.add_run("«Платёжный баланс» (国际收支平衡表)")
    r.italic = True
    r.font.size = Pt(14)

    intro = doc.add_paragraph()
    intro.add_run(
        "Ниже приводится подробное объяснение содержания каждого из 45 слайдов на русском языке. "
        "Ключевые термины сопровождаются их оригинальным китайским написанием в скобках."
    )

    doc.add_paragraph()

    for number, heading, paragraphs in SLIDES:
        h = doc.add_heading(level=1)
        run = h.add_run(f"Слайд {number}. {heading}")
        for p_text in paragraphs:
            p = doc.add_paragraph()
            p.add_run(p_text)
        doc.add_paragraph()

    out = "Объяснения_к_слайдам_RU_ZH.docx"
    doc.save(out)
    print(f"Saved: {out}")


if __name__ == "__main__":
    main()
